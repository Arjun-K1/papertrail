// PaperTrail service worker. Cache-first for the app shell and static files.
// The digest itself is a self-contained HTML file, so a saved digest works
// offline with no service worker at all.
var CACHE = "papertrail-v1";
var SHELL = ["/", "/static/app.css", "/static/app.js", "/static/manifest.json", "/digest.txt"];

self.addEventListener("install", function (event) {
  event.waitUntil(caches.open(CACHE).then(function (cache) {
    return cache.addAll(SHELL);
  }));
});

self.addEventListener("activate", function (event) {
  event.waitUntil(caches.keys().then(function (keys) {
    return Promise.all(keys.filter(function (k) { return k !== CACHE; })
      .map(function (k) { return caches.delete(k); }));
  }));
});

self.addEventListener("fetch", function (event) {
  if (event.request.method !== "GET") return;
  event.respondWith(
    caches.match(event.request).then(function (hit) {
      return hit || fetch(event.request).then(function (res) {
        var copy = res.clone();
        caches.open(CACHE).then(function (cache) { cache.put(event.request, copy); });
        return res;
      }).catch(function () { return caches.match("/"); });
    })
  );
});
